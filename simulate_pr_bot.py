"""
CostGuard AI DevOps PR Bot Simulator (Sweep.dev style)
Course: CSE 4011 - Intelligent Developer Tools & AI DevOps

Simulates:
1. GitHub Pull Request trigger (PR #42: "Optimize System Prompt")
2. Headless execution of CostGuard regression gate with Observability Tracing
3. Outcome Economics (Cost per Task vs Cost per Success)
4. Automated AI Review Comment generation powered by Live LLM Engine
"""

import json
from costguard.economics import compare_workloads
from costguard.llm import LLMMessage, default_llm_client
from costguard.models import ComparisonRequest
from costguard.observability import tracer

def main():
    print("=" * 72)
    print("  CostGuard: GitHub Actions CI/CD Automated PR Review Bot")
    print("  Emulates: Sweep.dev / CodiumAI AI-augmented CI/CD PR Automation")
    print("=" * 72)

    print("\n[GITHUB EVENT] Triggered: pull_request (opened)")
    print("  -> Repository:  lazinWolf/CostGuard")
    print("  -> PR #42:      'feat: enhance prompt with detailed instructions'")
    print("  -> Author:      dev-contributor")
    print("  -> Base Branch: main  <--  Head Branch: feature/new-prompt")

    print("\n[GITHUB ACTIONS] Running Job: 'CostGuard Economic Regression Gate'...")
    print("  -> Step 1: Checking out code... [OK]")
    print("  -> Step 2: Running test suite (32 tests)... [OK]")
    print("  -> Step 3: Executing CostGuard gate CLI & Observability Tracer...")

    with open("examples/comparison.json", "r") as f:
        data = json.load(f)

    with tracer.start_trace("pr_bot_ci_gate_review", metadata={"pr": 42}) as trace:
        with tracer.start_span("economic_gate_evaluation", kind="evaluation") as gate_span:
            req = ComparisonRequest.model_validate(data)
            report = compare_workloads(req)
            gate_span.set_attribute("policy_status", report.policy.status)

    cost_base = report.cost_per_request_usd.baseline
    cost_cand = report.cost_per_request_usd.candidate
    cost_delta = report.cost_per_request_usd.delta_percent
    out = report.outcome_economics

    # Generate live LLM automated review diagnosis
    llm_review_prompt = [
        LLMMessage(role="system", content="You are CostGuard's automated PR review bot (Sweep.dev style). Formulate a constructive diagnosis of this cost regression."),
        LLMMessage(role="user", content=f"PR #42 cost increased by {cost_delta}% ($0.0200 -> $0.0250). Quality gained +5%. Provide concise action items.")
    ]
    llm_res = default_llm_client.chat_completion(llm_review_prompt)

    print("\n[AUTOMATED PR COMMENT GENERATED BY COSTGUARD BOT]:")
    print("-" * 72)
    print("### [CostGuard AI DevOps Regression Analysis (PR #42)]")
    print(f"*Observability Trace: `{trace.trace_id}` | LLM Engine: `{llm_res.provider}/{llm_res.model}`*")
    print()
    print("| Metric | Baseline (`main`) | Candidate (PR) | Delta | CI/CD Decision |")
    print("| :--- | :---: | :---: | :---: | :---: |")
    print(f"| **Cost / Request** | ${cost_base:.4f} | ${cost_cand:.4f} | **+{cost_delta:.1f}%** | [FAIL] Exceeds Policy (<=20%) |")
    if out:
        print(f"| **Cost / Successful Task (ECSO)** | ${out.baseline.cost_per_successful_task_usd:.4f} | ${out.candidate.cost_per_successful_task_usd:.4f} | **+{out.cost_per_successful_task.delta_percent or 0:.1f}%** | [FAIL] Unit Economics Regression |")
        print(f"| **Task Success Rate** | {out.baseline.success_rate_percent}% | {out.candidate.success_rate_percent}% | **+{out.success_rate.delta_percent or 0:.1f}%** | Parity |")
    print(f"| **Mean Latency** | 1000 ms | 1200 ms | **+20.0%** | [WARN] Latency Increase |")
    print(f"| **Task Quality** | 0.80 | 0.84 | **+5.0%** | Marginal Improvement |")
    print(f"| **Monthly Spend Impact** | $2,000 | $2,500 | **+$500/mo** | Budget Breach |")
    print()
    print("> [ALERT] POLICY FAILURE: Cost increase 25.00% exceeds configured 20% limit.")
    print(">")
    print("> [Live AI Investigator Diagnosis]:")
    print(f"> {llm_res.content}")
    print("-" * 72)

    print("\n[ENFORCEMENT ACTION]:")
    print("  [-] GitHub Check: CostGuard Economic Gate -> FAILED (Exit Code 1)")
    print("  [-] Pull Request Merge: BLOCKED until regression is resolved.")
    print(f"  [-] Telemetry: Trace logged with {len(trace.spans)} spans ({llm_res.latency_ms}ms generation latency)")
    print("\n[OK] CI/CD PR Bot Simulation Complete.")
    print("=" * 72)

if __name__ == "__main__":
    main()
